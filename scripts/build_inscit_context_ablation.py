#!/usr/bin/env python3
"""Build paired static and frozen-model-simulated dynamic InSCIT datasets.

The two Parquet views emitted by this script have identical current queries,
answer references, evidence labels, and pair identifiers.  Only their public
conversation histories differ.  Static histories use the first released
``directAnswer`` reference; dynamic histories are generated by either a frozen
GPT-4.1 agent or a locally served frozen Qwen model, together with a local
top-k retriever and a relevance-only user judge.

No API credential is accepted on the command line.  The OpenAI provider reads
``OPENAI_API_KEY`` from the environment; the local provider needs no secret.
Successful external calls are cached by a content hash, so ``--resume`` can
safely continue after interruption without repeating completed calls.
"""

