def _status_code(error: BaseException) -> int | None:
    value = getattr(error, "status_code", None)
    if value is None:
        response = getattr(error, "response", None)
        value = getattr(response, "status_code", None)
    try:
        return int(value) if value is not None else None
    except (TypeError, ValueError):
        return None


def is_transient_error(error: BaseException) -> bool:
    status = _status_code(error)
    if status in {408, 429} or (status is not None and 500 <= status <= 599):
        return True
    if status is not None:
        return False
    names = {cls.__name__ for cls in type(error).__mro__}
    transient_names = {
        "APIConnectionError",
        "APITimeoutError",
        "RateLimitError",
        "InternalServerError",
        "ConnectError",
        "ConnectTimeout",
        "ReadTimeout",
        "ConnectionError",
        "Timeout",
    }
    return bool(names & transient_names) or isinstance(
        error,
        (requests.ConnectionError, requests.Timeout, TimeoutError, ConnectionError),
    )


class RetryController:
    """Retry transient external failures, with 0 meaning no retry limit."""

    def __init__(
        self,
        *,
        logger: logging.Logger,
        max_transient_retries: int,
        sleep: Callable[[float], None] = time.sleep,
        jitter: Callable[[], float] = random.random,
    ) -> None:
        if max_transient_retries < 0:
            raise ValueError("max_transient_retries must be >= 0")
        self.logger = logger
        self.max_transient_retries = max_transient_retries
        self.sleep = sleep
        self.jitter = jitter
        self._lock = threading.Lock()
        self._stats: dict[str, dict[str, float]] = defaultdict(
            lambda: {"transient_failures": 0.0, "wait_seconds": 0.0, "recoveries": 0.0}
        )
        self._context_stats: dict[tuple[str, str], dict[str, dict[str, float]]] = defaultdict(
            lambda: defaultdict(
                lambda: {"transient_failures": 0.0, "wait_seconds": 0.0, "recoveries": 0.0}
            )
        )

    def run(self, operation: Callable[[], T], context: RetryContext) -> T:
        started = time.monotonic()
        failures = 0
        next_heartbeat = 300.0
        while True:
            try:
                value = operation()
                if failures:
                    elapsed = time.monotonic() - started
                    self.logger.info(
                        "[DynamicBuilder][recovered] split=%s conversation=%s turn=%s "
                        "stage=%s attempt=%s elapsed=%s",
                        context.split,
                        context.conversation,
                        context.turn,
                        context.stage,
                        failures + 1,
                        _duration(elapsed),
                    )
                    with self._lock:
                        self._stats[context.stage]["recoveries"] += 1
                        self._context_stats[(context.split, context.conversation)][context.stage][
                            "recoveries"
                        ] += 1
                return value
            except KeyboardInterrupt:
                raise
            except BuildError:
                # Schema/format/programming failures are not connection
                # failures and must be handled by their bounded caller or
                # surfaced immediately.  Never turn them into infinite retry.
                raise
            except BaseException as error:
                if not is_transient_error(error):
                    status = _status_code(error)
                    raise PermanentExternalError(
                        f"Permanent external failure at {context.stage}: "
                        f"{type(error).__name__} status={status}: {error}"
                    ) from error
                failures += 1
                if self.max_transient_retries and failures > self.max_transient_retries:
                    raise BuildError(
                        f"Transient retry limit exceeded at {context.stage}: "
                        f"{type(error).__name__}"
                    ) from error
                base = (2, 4, 8, 16, 30, 60)[min(failures - 1, 5)]
                wait_seconds = base * (0.9 + 0.2 * self.jitter())
                elapsed = time.monotonic() - started
                status = _status_code(error)
                self.logger.warning(
                    "[DynamicBuilder][retry] split=%s conversation=%s turn=%s stage=%s "
                    "attempt=%s error=%s http_status=%s elapsed=%s next_retry_in=%.1fs",
                    context.split,
                    context.conversation,
                    context.turn,
                    context.stage,
                    failures,
                    type(error).__name__,
                    status,
                    _duration(elapsed),
                    wait_seconds,
                )
                if elapsed >= next_heartbeat:
                    self.logger.warning(
                        "[DynamicBuilder][heartbeat] split=%s conversation=%s turn=%s "
                        "stage=%s still_retrying=true failures=%s elapsed=%s",
                        context.split,
                        context.conversation,
                        context.turn,
                        context.stage,
                        failures,
                        _duration(elapsed),
                    )
                    next_heartbeat += 300.0
                with self._lock:
                    self._stats[context.stage]["transient_failures"] += 1
                    self._stats[context.stage]["wait_seconds"] += wait_seconds
                    context_values = self._context_stats[(context.split, context.conversation)][
                        context.stage
                    ]
                    context_values["transient_failures"] += 1
                    context_values["wait_seconds"] += wait_seconds
                self.sleep(wait_seconds)

    def summary(self) -> dict[str, dict[str, float | int]]:
        with self._lock:
            return {
                stage: {
                    "transient_failures": int(values["transient_failures"]),
                    "wait_seconds": round(values["wait_seconds"], 3),
                    "recoveries": int(values["recoveries"]),
                }
                for stage, values in sorted(self._stats.items())
            }

    def summary_for(self, split: str, conversation: str) -> dict[str, dict[str, float | int]]:
        with self._lock:
            stages = self._context_stats.get((split, conversation), {})
            return {
                stage: {
                    "transient_failures": int(values["transient_failures"]),
                    "wait_seconds": round(values["wait_seconds"], 3),
                    "recoveries": int(values["recoveries"]),
                }
                for stage, values in sorted(stages.items())
            }


def _duration(seconds: float) -> str:
    total = max(0, int(seconds))
    hours, remainder = divmod(total, 3600)
    minutes, secs = divmod(remainder, 60)
    return f"{hours:02d}:{minutes:02d}:{secs:02d}"


class RequestCache:
    """Thread-safe content-addressed cache for successful external calls."""

    def __init__(self, root: Path, signature: str) -> None:
        self.root = root
        self.signature = signature
        self.root.mkdir(parents=True, exist_ok=True)
        self._guard = threading.Lock()
        self._locks: dict[str, threading.Lock] = {}

    def _path(self, kind: str, payload: Any) -> Path:
        key = sha256_json({"signature": self.signature, "kind": kind, "payload": payload})
        return self.root / kind / f"{key}.json"

    def get_or_compute(self, kind: str, payload: Any, operation: Callable[[], T]) -> T:
        path = self._path(kind, payload)
        with self._guard:
            lock = self._locks.setdefault(str(path), threading.Lock())
        with lock:
            if path.is_file():
                record = json.loads(path.read_text(encoding="utf-8"))
                return record["result"]
            result = operation()
            atomic_write_json(
                path,
                {
                    "kind": kind,
                    "created_at": utc_now(),
                    "payload_hash": sha256_json(payload),
                    "result": result,
                },
            )
            return result


def public_transcript(messages: Sequence[Mapping[str, str]]) -> str:
    return "\n".join(f"{message['role']}: {message['content']}" for message in messages)


def _response_output_text(response: Any) -> str:
    text = getattr(response, "output_text", None)
    if text:
        return str(text)
    pieces: list[str] = []
    for item in getattr(response, "output", []) or []:
        for content in getattr(item, "content", []) or []:
            value = getattr(content, "text", None)
            if value:
                pieces.append(str(value))
    return "\n".join(pieces)


def _chat_completion_text(response: Any) -> str:
    """Return text from an OpenAI-compatible chat-completions response."""

    choices = getattr(response, "choices", None) or []
    if not choices:
        raise ModelFormatError("Chat-completions response has no choices")
    message = getattr(choices[0], "message", None)
    content = getattr(message, "content", None)
    if isinstance(content, str) and content.strip():
        return content
    raise ModelFormatError("Chat-completions response has no text content")


def _json_object_from_text(text: str) -> dict[str, Any]:
    """Parse the first JSON object, tolerating Markdown fences from local LLMs."""

    candidate = text.strip()
    if candidate.startswith("```"):
        candidate = re.sub(r"^```(?:json)?\s*", "", candidate, flags=re.IGNORECASE)
        candidate = re.sub(r"\s*```$", "", candidate)
    decoder = json.JSONDecoder()
    for offset, character in enumerate(candidate):
        if character != "{":
            continue
        try:
            value, _ = decoder.raw_decode(candidate[offset:])
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            return value
    raise ModelFormatError("Model response does not contain a valid JSON object")


def _function_call(response: Any, name: str) -> dict[str, str]:
    calls = [
        item
        for item in getattr(response, "output", []) or []
        if getattr(item, "type", "") == "function_call" and getattr(item, "name", "") == name
    ]
    if len(calls) != 1:
        raise ModelFormatError(f"GPT response produced {len(calls)} calls to required tool {name!r}")
    item = calls[0]
    return {
        "call_id": str(getattr(item, "call_id")),
        "name": name,
        "arguments": str(getattr(item, "arguments")),
    }


class OpenAIDynamicBackend:
    """GPT-4.1 generator, directness judge, and dependency checker."""

    def __init__(
        self,
        *,
        model: str,
        retriever_url: str,
        topk: int,
        format_retries: int,
        cache: RequestCache,
        retry: RetryController,
    ) -> None:
        if not os.environ.get("OPENAI_API_KEY"):
            raise BuildError("OPENAI_API_KEY is not set")
        try:
            from openai import OpenAI
        except ImportError as error:
            raise BuildError(
                "The context builder requires the official openai Python package. "
                "Install requirements-context-ablation.txt."
            ) from error
        self._OpenAI = OpenAI
        self._thread_local = threading.local()
        self.model = model
        self.retriever_url = retriever_url
        self.topk = topk
        self.format_retries = format_retries
        self.cache = cache
        self.retry = retry

    def _client(self) -> Any:
        client = getattr(self._thread_local, "client", None)
        if client is None:
            # Disable opaque SDK retries so every transient failure is logged
            # and counted by RetryController. A bounded request timeout also
            # guarantees that the five-minute retry heartbeat can advance.
            client = self._OpenAI(timeout=60.0, max_retries=0)
            self._thread_local.client = client
        return client

    def _cached_openai(
        self,
        *,
        kind: str,
        payload: Any,
        context: RetryContext,
        request: Callable[[], T],
    ) -> T:
        return self.cache.get_or_compute(
            kind,
            payload,
            lambda: self.retry.run(request, context),
        )

    def _retrieve(self, query: str, context: RetryContext) -> list[dict[str, Any]]:
        payload = {"url": self.retriever_url, "query": query, "topk": self.topk}

        def request() -> list[dict[str, Any]]:
            response = requests.post(
                self.retriever_url,
                json={"queries": [query], "topk": self.topk, "return_scores": True},
                timeout=60,
            )
            if response.status_code >= 400:
                response.raise_for_status()
            body = response.json()
            results = body.get("result")
            if not isinstance(results, list) or not results or not isinstance(results[0], list):
                raise ModelFormatError("Retriever returned an invalid result shape")
            passages: list[dict[str, Any]] = []
            for value in results[0]:
                if isinstance(value, Mapping) and isinstance(value.get("document"), Mapping):
                    passage = dict(value["document"])
                    passage["score"] = value.get("score")
                elif isinstance(value, Mapping):
                    passage = dict(value)
                else:
                    passage = {"passage_text": str(value)}
                passages.append(passage)
            return passages[: self.topk]

        return self.cache.get_or_compute(
            "retriever",
            payload,
            lambda: self.retry.run(
                request,
                RetryContext(context.split, context.conversation, context.turn, "retriever"),
            ),
        )

    def _one_answer(
        self,
        messages: Sequence[Mapping[str, str]],
        context: RetryContext,
        answer_index: int,
    ) -> dict[str, Any]:
        transcript = public_transcript(messages)
        tool = {
            "type": "function",
            "name": "retrieve",
            "description": "Retrieve the top passages for one standalone conversational-search query.",
            "parameters": {
                "type": "object",
                "properties": {"query": {"type": "string"}},
                "required": ["query"],
                "additionalProperties": False,
            },
            "strict": True,
        }
        call: dict[str, str] | None = None
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: emit exactly one valid retrieve function call with a non-empty query."
            )
            instructions = SYSTEM_AGENT_INSTRUCTIONS + repair_note
            payload = {
                "model": self.model,
                "instructions": instructions,
                "transcript": transcript,
                "answer_index": answer_index,
                "format_attempt": format_attempt,
            }

            def request_call() -> dict[str, str]:
                response = self._client().responses.create(
                    model=self.model,
                    instructions=instructions,
                    input=[{"role": "user", "content": transcript}],
                    tools=[tool],
                    tool_choice={"type": "function", "name": "retrieve"},
                    parallel_tool_calls=False,
                    temperature=0,
                )
                return _function_call(response, "retrieve")

            try:
                call = self._cached_openai(
                    kind="openai_tool_call",
                    payload=payload,
                    context=RetryContext(context.split, context.conversation, context.turn, "system_search_query"),
                    request=request_call,
                )
                arguments = json.loads(call["arguments"])
                query = str(arguments.get("query", "")).strip()
                if not query:
                    raise ModelFormatError("retrieve query is empty")
                break
            except (json.JSONDecodeError, ModelFormatError):
                if format_attempt == self.format_retries:
                    raise ModelFormatError(
                        f"System search query remained malformed after {self.format_retries} attempts"
                    )
        assert call is not None
        passages = self._retrieve(query, context)

        raw_answer = ""
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: return exactly one non-empty <answer>...</answer> block."
            )
            instructions = SYSTEM_AGENT_INSTRUCTIONS + repair_note
            payload = {
                "model": self.model,
                "instructions": instructions,
                "transcript": transcript,
                "tool_call": call,
                "passages": passages,
                "answer_index": answer_index,
                "format_attempt": format_attempt,
            }

            def request_answer() -> str:
                response = self._client().responses.create(
                    model=self.model,
                    instructions=instructions,
                    input=[
                        {"role": "user", "content": transcript},
                        {
                            "type": "function_call",
                            "call_id": call["call_id"],
                            "name": "retrieve",
                            "arguments": call["arguments"],
                        },
                        {
                            "type": "function_call_output",
                            "call_id": call["call_id"],
                            "output": json.dumps(passages, ensure_ascii=False),
                        },
                    ],
                    tools=[tool],
                    tool_choice="none",
                    temperature=0,
                )
                return _response_output_text(response)

            raw_answer = self._cached_openai(
                kind="openai_system_answer",
                payload=payload,
                context=RetryContext(context.split, context.conversation, context.turn, "system_answer"),
                request=request_answer,
            )
            match = ANSWER_PATTERN.search(raw_answer)
            if match and match.group(1).strip():
                return {
                    "search_query": query,
                    "retrieved_passages": passages,
                    "raw_answer": raw_answer,
                    "answer": match.group(1).strip(),
                }
        raise ModelFormatError(
            f"System answer lacked a non-empty <answer> after {self.format_retries} attempts"
        )

    def _judge(
        self,
        *,
        current_query: str,
        public_history: Sequence[Mapping[str, str]],
        answer: str,
        context: RetryContext,
        answer_index: int,
    ) -> dict[str, Any]:
        schema = {
            "type": "object",
            "properties": {
                "addresses_query": {"type": "boolean"},
                "feedback": {"type": "string"},
                "reason": {"type": "string"},
            },
            "required": ["addresses_query", "feedback", "reason"],
            "additionalProperties": False,
        }
        input_payload = {
            "current_query": current_query,
            "public_conversation": list(public_history),
            "assistant_response": answer,
        }
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: return schema-valid JSON and provide non-empty feedback when addresses_query is false."
            )
            instructions = USER_JUDGE_INSTRUCTIONS + repair_note
            payload = {
                "model": self.model,
                "instructions": instructions,
                "input": input_payload,
                "answer_index": answer_index,
                "format_attempt": format_attempt,
            }

            def request() -> str:
                response = self._client().responses.create(
                    model=self.model,
                    instructions=instructions,
                    input=json.dumps(input_payload, ensure_ascii=False),
                    text={
                        "format": {
                            "type": "json_schema",
                            "name": "directness_judgement",
                            "strict": True,
                            "schema": schema,
                        }
                    },
                    temperature=0,
                )
                return _response_output_text(response)

            raw = self._cached_openai(
                kind="openai_user_judge",
                payload=payload,
                context=RetryContext(context.split, context.conversation, context.turn, "user_judge"),
                request=request,
            )
            try:
                value = json.loads(raw)
                if not isinstance(value.get("addresses_query"), bool):
                    raise ModelFormatError("addresses_query is not boolean")
                if not value["addresses_query"] and not str(value.get("feedback", "")).strip():
                    raise ModelFormatError("off-topic judgement has empty feedback")
                return value
            except (json.JSONDecodeError, AttributeError, ModelFormatError):
                if format_attempt == self.format_retries:
                    raise ModelFormatError(
                        f"User judgement remained malformed after {self.format_retries} attempts"
                    )
        raise AssertionError("unreachable")

    def generate_turn(
        self,
        *,
        public_history: Sequence[Mapping[str, str]],
        current_query: str,
        context: RetryContext,
        max_feedback_rounds: int,
    ) -> dict[str, Any]:
        messages = [dict(message) for message in public_history]
        messages.append({"role": "User", "content": current_query})
        attempts: list[dict[str, Any]] = []
        for answer_index in range(max_feedback_rounds + 1):
            generated = self._one_answer(messages, context, answer_index)
            messages.append({"role": "Assistant", "content": generated["answer"]})
            attempt = dict(generated)
            attempt["answer_index"] = answer_index
            if answer_index < max_feedback_rounds:
                judgement = self._judge(
                    current_query=current_query,
                    public_history=messages,
                    answer=generated["answer"],
                    context=context,
                    answer_index=answer_index,
                )
                attempt["judgement"] = judgement
                attempts.append(attempt)
                if judgement["addresses_query"]:
                    return {
                        "public_history": messages,
                        "final_answer": generated["answer"],
                        "attempts": attempts,
                        "accepted_unjudged": False,
                    }
                feedback = str(judgement["feedback"]).strip()
                messages.append({"role": "User", "content": feedback})
            else:
                attempts.append(attempt)
                return {
                    "public_history": messages,
                    "final_answer": generated["answer"],
                    "attempts": attempts,
                    "accepted_unjudged": True,
                }
        raise AssertionError("unreachable")

    def check_dependency(
        self,
        *,
        next_query: str,
        prior_gold_answers: Sequence[Mapping[str, Any]],
        dynamic_history: Sequence[Mapping[str, str]],
        context: RetryContext,
    ) -> dict[str, Any]:
        schema = {
            "type": "object",
            "properties": {
                "depends_on_prior_gold": {"type": "boolean"},
                "required_turn_indices": {"type": "array", "items": {"type": "integer"}},
                "dynamic_history_sufficient": {"type": "boolean"},
                "reason": {"type": "string"},
            },
            "required": [
                "depends_on_prior_gold",
                "required_turn_indices",
                "dynamic_history_sufficient",
                "reason",
            ],
            "additionalProperties": False,
        }
        input_payload = {
            "next_query": next_query,
            "prior_ground_truth_answers": list(prior_gold_answers),
            "generated_public_conversation": list(dynamic_history),
        }
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: return schema-valid JSON with valid zero-based required_turn_indices."
            )
            instructions = DEPENDENCY_INSTRUCTIONS + repair_note
            payload = {
                "model": self.model,
                "instructions": instructions,
                "input": input_payload,
                "format_attempt": format_attempt,
            }

            def request() -> str:
                response = self._client().responses.create(
                    model=self.model,
                    instructions=instructions,
                    input=json.dumps(input_payload, ensure_ascii=False),
                    text={
                        "format": {
                            "type": "json_schema",
                            "name": "history_dependency",
                            "strict": True,
                            "schema": schema,
                        }
                    },
                    temperature=0,
                )
                return _response_output_text(response)

            raw = self._cached_openai(
                kind="openai_dependency",
                payload=payload,
                context=RetryContext(context.split, context.conversation, context.turn, "dependency_checker"),
                request=request,
            )
            try:
                value = json.loads(raw)
                if not isinstance(value.get("depends_on_prior_gold"), bool):
                    raise ModelFormatError("depends_on_prior_gold is not boolean")
                if not isinstance(value.get("dynamic_history_sufficient"), bool):
                    raise ModelFormatError("dynamic_history_sufficient is not boolean")
                if not isinstance(value.get("required_turn_indices"), list):
                    raise ModelFormatError("required_turn_indices is not a list")
                required = value["required_turn_indices"]
                if any(
                    not isinstance(index, int) or not 0 <= index < len(prior_gold_answers)
                    for index in required
                ):
                    raise ModelFormatError("required_turn_indices contains an invalid prior turn index")
                if value["depends_on_prior_gold"] and not required:
                    raise ModelFormatError("dependent query has no required_turn_indices")
                if not value["depends_on_prior_gold"] and required:
                    raise ModelFormatError("independent query has required_turn_indices")
                return value
            except (json.JSONDecodeError, AttributeError, ModelFormatError):
                if format_attempt == self.format_retries:
                    raise ModelFormatError(
                        f"Dependency result remained malformed after {self.format_retries} attempts"
                    )
        raise AssertionError("unreachable")


class LocalQwenDynamicBackend(OpenAIDynamicBackend):
    """Qwen backend served by an OpenAI-compatible local vLLM endpoint.

    Retrieval is enforced by the program rather than delegated to optional
    tool-calling support: Qwen first emits one standalone query, the builder
    calls the retriever exactly once, and Qwen then answers from the returned
    top-k passages.
    """

    def __init__(
        self,
        *,
        model: str,
        base_url: str,
        retriever_url: str,
        topk: int,
        format_retries: int,
        max_output_tokens: int,
        request_timeout_seconds: float,
        cache: RequestCache,
        retry: RetryController,
    ) -> None:
        try:
            from openai import OpenAI
        except ImportError as error:
            raise BuildError(
                "The local Qwen backend uses the official openai Python client for the "
                "vLLM-compatible endpoint. Install requirements-context-ablation.txt."
            ) from error
        normalized_base_url = base_url.rstrip("/")
        if not normalized_base_url.endswith("/v1"):
            normalized_base_url += "/v1"
        self._OpenAI = OpenAI
        self._thread_local = threading.local()
        self.model = model
        self.base_url = normalized_base_url
        self.retriever_url = retriever_url
        self.topk = topk
        self.format_retries = format_retries
        self.max_output_tokens = max_output_tokens
        self.request_timeout_seconds = request_timeout_seconds
        self.cache = cache
        self.retry = retry

    def _client(self) -> Any:
        client = getattr(self._thread_local, "client", None)
        if client is None:
            client = self._OpenAI(
                api_key=os.environ.get("LOCAL_LLM_API_KEY", "EMPTY"),
                base_url=self.base_url,
                timeout=self.request_timeout_seconds,
                max_retries=0,
            )
            self._thread_local.client = client
        return client

    def _chat(self, *, instructions: str, user_content: str, max_tokens: int) -> str:
        response = self._client().chat.completions.create(
            model=self.model,
            messages=[
                {"role": "system", "content": instructions},
                {"role": "user", "content": user_content},
            ],
            temperature=0,
            seed=42,
            max_tokens=max_tokens,
        )
        return _chat_completion_text(response)

    def _one_answer(
        self,
        messages: Sequence[Mapping[str, str]],
        context: RetryContext,
        answer_index: int,
    ) -> dict[str, Any]:
        transcript = public_transcript(messages)
        query = ""
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: output only one JSON object with one non-empty string field named query."
            )
            instructions = LOCAL_SEARCH_QUERY_INSTRUCTIONS + repair_note
            payload = {
                "provider": "local-qwen",
                "model": self.model,
                "base_url": self.base_url,
                "instructions": instructions,
                "transcript": transcript,
                "answer_index": answer_index,
                "format_attempt": format_attempt,
            }

            def request_query() -> str:
                return self._chat(
                    instructions=instructions,
                    user_content=canonical_json({"public_conversation": transcript}),
                    max_tokens=min(192, self.max_output_tokens),
                )

            raw_query = self._cached_openai(
                kind="local_qwen_search_query",
                payload=payload,
                context=RetryContext(
                    context.split, context.conversation, context.turn, "system_search_query"
                ),
                request=request_query,
            )
            try:
                query_value = _json_object_from_text(raw_query)
                if set(query_value) != {"query"}:
                    raise ModelFormatError("search-query JSON must contain only the query field")
                query = str(query_value.get("query", "")).strip()
                if not query:
                    raise ModelFormatError("search query is empty")
                break
            except ModelFormatError:
                if format_attempt == self.format_retries:
                    raise ModelFormatError(
                        f"Local Qwen search query remained malformed after "
                        f"{self.format_retries} attempts"
                    )

        passages = self._retrieve(query, context)
        answer_input = {
            "public_conversation": transcript,
            "standalone_search_query": query,
            "retrieved_passages": passages,
        }
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: output exactly one non-empty <answer>...</answer> block."
            )
            instructions = LOCAL_ANSWER_INSTRUCTIONS + repair_note
            payload = {
                "provider": "local-qwen",
                "model": self.model,
                "base_url": self.base_url,
                "instructions": instructions,
                "input": answer_input,
                "answer_index": answer_index,
                "format_attempt": format_attempt,
            }

            def request_answer() -> str:
                return self._chat(
                    instructions=instructions,
                    user_content=json.dumps(answer_input, ensure_ascii=False),
                    max_tokens=self.max_output_tokens,
                )

            raw_answer = self._cached_openai(
                kind="local_qwen_system_answer",
                payload=payload,
                context=RetryContext(
                    context.split, context.conversation, context.turn, "system_answer"
                ),
                request=request_answer,
            )
            matches = ANSWER_PATTERN.findall(raw_answer)
            if len(matches) == 1 and matches[0].strip():
                return {
                    "search_query": query,
                    "retrieved_passages": passages,
                    "raw_answer": raw_answer,
                    "answer": matches[0].strip(),
                }
        raise ModelFormatError(
            f"Local Qwen answer lacked exactly one non-empty <answer> block after "
            f"{self.format_retries} attempts"
        )

    def _judge(
        self,
        *,
        current_query: str,
        public_history: Sequence[Mapping[str, str]],
        answer: str,
        context: RetryContext,
        answer_index: int,
    ) -> dict[str, Any]:
        input_payload = {
            "current_query": current_query,
            "public_conversation": list(public_history),
            "assistant_response": answer,
        }
        schema_note = (
            '\nReturn JSON only: {"addresses_query": true|false, "feedback": "...", '
            '"reason": "..."}. feedback must be non-empty when addresses_query is false.'
        )
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: obey the JSON schema exactly; do not use Markdown fences."
            )
            instructions = USER_JUDGE_INSTRUCTIONS + schema_note + repair_note
            payload = {
                "provider": "local-qwen",
                "model": self.model,
                "base_url": self.base_url,
                "instructions": instructions,
                "input": input_payload,
                "answer_index": answer_index,
                "format_attempt": format_attempt,
            }

            def request() -> str:
                return self._chat(
                    instructions=instructions,
                    user_content=json.dumps(input_payload, ensure_ascii=False),
                    max_tokens=min(384, self.max_output_tokens),
                )

            raw = self._cached_openai(
                kind="local_qwen_user_judge",
                payload=payload,
                context=RetryContext(
                    context.split, context.conversation, context.turn, "user_judge"
                ),
                request=request,
            )
            try:
                value = _json_object_from_text(raw)
                if set(value) != {"addresses_query", "feedback", "reason"}:
                    raise ModelFormatError("user judgement has missing or extra fields")
                if not isinstance(value.get("addresses_query"), bool):
                    raise ModelFormatError("addresses_query is not boolean")
                if not isinstance(value.get("feedback"), str) or not isinstance(
                    value.get("reason"), str
                ):
                    raise ModelFormatError("feedback and reason must be strings")
                if not value["addresses_query"] and not str(value.get("feedback", "")).strip():
                    raise ModelFormatError("off-topic judgement has empty feedback")
                value["feedback"] = str(value.get("feedback", "")).strip()
                value["reason"] = str(value.get("reason", "")).strip()
                return value
            except (AttributeError, ModelFormatError):
                if format_attempt == self.format_retries:
                    raise ModelFormatError(
                        f"Local Qwen user judgement remained malformed after "
                        f"{self.format_retries} attempts"
                    )
        raise AssertionError("unreachable")

    def check_dependency(
        self,
        *,
        next_query: str,
        prior_gold_answers: Sequence[Mapping[str, Any]],
        dynamic_history: Sequence[Mapping[str, str]],
        context: RetryContext,
    ) -> dict[str, Any]:
        input_payload = {
            "next_query": next_query,
            "prior_ground_truth_answers": list(prior_gold_answers),
            "generated_public_conversation": list(dynamic_history),
        }
        schema_note = (
            '\nReturn JSON only: {"depends_on_prior_gold": true|false, '
            '"required_turn_indices": [0], "dynamic_history_sufficient": true|false, '
            '"reason": "..."}. Indices are zero-based.'
        )
        for format_attempt in range(1, self.format_retries + 1):
            repair_note = (
                ""
                if format_attempt == 1
                else "\nFormat repair: obey the JSON schema exactly; do not use Markdown fences."
            )
            instructions = DEPENDENCY_INSTRUCTIONS + schema_note + repair_note
            payload = {
                "provider": "local-qwen",
                "model": self.model,
                "base_url": self.base_url,
                "instructions": instructions,
                "input": input_payload,
                "format_attempt": format_attempt,
            }

            def request() -> str:
                return self._chat(
                    instructions=instructions,
                    user_content=json.dumps(input_payload, ensure_ascii=False),
                    max_tokens=min(512, self.max_output_tokens),
                )

            raw = self._cached_openai(
                kind="local_qwen_dependency",
                payload=payload,
                context=RetryContext(
                    context.split, context.conversation, context.turn, "dependency_checker"
                ),
                request=request,
            )
            try:
                value = _json_object_from_text(raw)
                expected_fields = {
                    "depends_on_prior_gold",
                    "required_turn_indices",
                    "dynamic_history_sufficient",
                    "reason",
                }
                if set(value) != expected_fields:
                    raise ModelFormatError("dependency result has missing or extra fields")
                if not isinstance(value.get("depends_on_prior_gold"), bool):
                    raise ModelFormatError("depends_on_prior_gold is not boolean")
                if not isinstance(value.get("dynamic_history_sufficient"), bool):
                    raise ModelFormatError("dynamic_history_sufficient is not boolean")
                required = value.get("required_turn_indices")
                if not isinstance(required, list):
                    raise ModelFormatError("required_turn_indices is not a list")
                if not isinstance(value.get("reason"), str):
                    raise ModelFormatError("dependency reason is not a string")
                if any(
                    not isinstance(index, int) or not 0 <= index < len(prior_gold_answers)
                    for index in required
                ):
                    raise ModelFormatError("required_turn_indices contains an invalid prior turn index")
                if value["depends_on_prior_gold"] and not required:
                    raise ModelFormatError("dependent query has no required_turn_indices")
                if not value["depends_on_prior_gold"] and required:
                    raise ModelFormatError("independent query has required_turn_indices")
                value["reason"] = str(value.get("reason", "")).strip()
                return value
            except (AttributeError, ModelFormatError):
                if format_attempt == self.format_retries:
                    raise ModelFormatError(
                        f"Local Qwen dependency result remained malformed after "
                        f"{self.format_retries} attempts"
                    )
        raise AssertionError("unreachable")


def direct_answer_turns(
    dialogue_id: str,
    turns: Sequence[Mapping[str, Any]],
    *,
    split: str,
) -> tuple[list[DirectTurn], list[dict[str, Any]]]:
    retained: list[DirectTurn] = []
    dropped: list[dict[str, Any]] = []
    for turn_index, turn in enumerate(turns):
        labels = turn.get("labels", [])
        direct_labels = [
            label
            for label in labels
            if isinstance(label, Mapping) and label.get("responseType") == "directAnswer"
        ]
        nonempty_direct_labels = [
            label for label in direct_labels if str(label.get("response", "") or "").strip()
        ]
        if not nonempty_direct_labels:
            for dropped_index in range(turn_index, len(turns)):
                dropped.append(
                    {
                        "split": split,
                        "dialogue_id": dialogue_id,
                        "source_turn_index": dropped_index,
                        "pair_id": f"{split}:{dialogue_id}:{dropped_index}",
                        "reason": (
                            "answer_prefix_filter"
                            if not direct_labels
                            else "answer_prefix_filter_empty_direct_answer"
                        ),
                    }
                )
            break
        context = turn.get("context", [])
        if not isinstance(context, Sequence) or isinstance(context, (str, bytes)) or not context:
            raise BuildError(f"{dialogue_id} turn {turn_index} has no current query in context")
        question = str(context[-1]).strip()
        candidates: list[dict[str, Any]] = []
        for label in nonempty_direct_labels:
            response = str(label.get("response", "") or "").strip()
            passage_ids: list[str] = []
            evidence_records = [
                dict(evidence)
                for evidence in label.get("evidence", []) or []
                if isinstance(evidence, Mapping)
            ]
            for evidence in evidence_records:
                if isinstance(evidence, Mapping):
                    passage_id = str(evidence.get("passage_id", "") or "").strip()
                    if passage_id and passage_id not in passage_ids:
                        passage_ids.append(passage_id)
            candidates.append(
                {
                    "response": response,
                    "action": "answer",
                    "passage_id": passage_ids,
                    "evidence": evidence_records,
                    "rewrite": question,
                }
            )
        retained.append(
            DirectTurn(
                source_turn_index=turn_index,
                question=question,
                primary_answer=candidates[0]["response"],
                candidates=candidates,
            )
        )
    return retained, dropped


def convagent_prompt(history: Sequence[Mapping[str, str]], question: str) -> str:
    context = public_transcript(history)
    return f"{CONVAGENT_INSTRUCTION}\nContext Begin: <context>{context}</context>.\nQuestion: {question}"


def make_row(
    *,
    split: str,
    dialogue_id: str,
    turn: DirectTurn,
    retained_index: int,
    variant: str,
    dependency_class: str,
    history: Sequence[Mapping[str, str]],
) -> dict[str, Any]:
    pair_id = f"{split}:{dialogue_id}:{turn.source_turn_index}"
    return {
        "data_source": "inscit",
        "prompt": [{"role": "user", "content": convagent_prompt(history, turn.question)}],
        "ability": "fact_reasoning",
        "reward_model": {"style": "rule", "ground_truth": turn.candidates},
        "extra_info": {
            "split": split,
            "index": pair_id,
            "pair_id": pair_id,
            "conversation_id": dialogue_id,
            "turn_index": retained_index,
            "source_turn_index": turn.source_turn_index,
            "context_variant": variant,
            "dependency_class": dependency_class,
        },
    }


def process_dialogue(
    *,
    dialogue_id: str,
    dialogue: Mapping[str, Any],
    split: str,
    backend: DynamicBackend,
    max_feedback_rounds: int,
    config_hash: str,
) -> BuildResult:
    turns, dropped = direct_answer_turns(dialogue_id, dialogue.get("turns", []), split=split)
    static_rows: list[dict[str, Any]] = []
    dynamic_rows: list[dict[str, Any]] = []
    static_history: list[dict[str, str]] = []
    dynamic_history: list[dict[str, str]] = []
    dependency_class = "first_turn"
    turn_audits: list[dict[str, Any]] = []

    for retained_index, turn in enumerate(turns):
        static_rows.append(
            make_row(
                split=split,
                dialogue_id=dialogue_id,
                turn=turn,
                retained_index=retained_index,
                variant="static",
                dependency_class=dependency_class,
                history=static_history,
            )
        )
        dynamic_rows.append(
            make_row(
                split=split,
                dialogue_id=dialogue_id,
                turn=turn,
                retained_index=retained_index,
                variant="dynamic",
                dependency_class=dependency_class,
                history=dynamic_history,
            )
        )
        turn_audit: dict[str, Any] = {
            "retained_turn_index": retained_index,
            "source_turn_index": turn.source_turn_index,
            "pair_id": f"{split}:{dialogue_id}:{turn.source_turn_index}",
            "question": turn.question,
            "direct_answer_references": [candidate["response"] for candidate in turn.candidates],
            "static_history_before": list(static_history),
            "dynamic_history_before": list(dynamic_history),
            "dependency_class": dependency_class,
        }
        turn_audits.append(turn_audit)

        if retained_index + 1 >= len(turns):
            break

        interaction = backend.generate_turn(
            public_history=dynamic_history,
            current_query=turn.question,
            context=RetryContext(split, dialogue_id, turn.source_turn_index, "system_answer"),
            max_feedback_rounds=max_feedback_rounds,
        )
        dynamic_history = [dict(message) for message in interaction["public_history"]]
        turn_audit["dynamic_interaction"] = interaction

        static_history.extend(
            [
                {"role": "User", "content": turn.question},
                {"role": "Assistant", "content": turn.primary_answer},
            ]
        )
        next_turn = turns[retained_index + 1]
        prior_gold = [
            {
                "turn_index": index,
                "question": value.question,
                "answers": [candidate["response"] for candidate in value.candidates],
            }
            for index, value in enumerate(turns[: retained_index + 1])
        ]
        decision = backend.check_dependency(
            next_query=next_turn.question,
            prior_gold_answers=prior_gold,
            dynamic_history=dynamic_history,
            context=RetryContext(split, dialogue_id, next_turn.source_turn_index, "dependency_checker"),
        )
        turn_audit["next_turn_dependency"] = decision
        dependent = bool(decision["depends_on_prior_gold"])
        sufficient = bool(decision["dynamic_history_sufficient"])
        if dependent and not sufficient:
            for value in turns[retained_index + 1 :]:
                dropped.append(
                    {
                        "split": split,
                        "dialogue_id": dialogue_id,
                        "source_turn_index": value.source_turn_index,
                        "pair_id": f"{split}:{dialogue_id}:{value.source_turn_index}",
                        "reason": "dynamic_dependency_missing",
                        "dependency_reason": str(decision.get("reason", "")),
                        "required_turn_indices": decision.get("required_turn_indices", []),
                    }
                )
            break
        dependency_class = "dependent_sufficient" if dependent else "independent"

    # Rows are appended before the dependency decision for the next turn. If
    # that gate fails, no next row has been appended, so both views remain
    # exactly paired without a second truncation pass.
    audit = {
        "status": "complete",
        "config_hash": config_hash,
        "completed_at": utc_now(),
        "split": split,
        "dialogue_id": dialogue_id,
        "source_turn_count": len(dialogue.get("turns", [])),
        "answer_prefix_turn_count": len(turns),
        "retained_turn_count": len(static_rows),
        "static_rows": static_rows,
        "dynamic_rows": dynamic_rows,
        "dropped": dropped,
        "turns": turn_audits,
    }
    return BuildResult(dialogue_id, static_rows, dynamic_rows, dropped, audit)


def validate_pairs(static_rows: Sequence[Mapping[str, Any]], dynamic_rows: Sequence[Mapping[str, Any]]) -> None:
    if len(static_rows) != len(dynamic_rows):
        raise BuildError(f"Static/dynamic row counts differ: {len(static_rows)} != {len(dynamic_rows)}")
    for static, dynamic in zip(static_rows, dynamic_rows):
        static_info = static["extra_info"]
        dynamic_info = dynamic["extra_info"]
        if static_info["pair_id"] != dynamic_info["pair_id"]:
            raise BuildError("Static/dynamic pair ordering differs")
        static_common_info = dict(static_info)
        dynamic_common_info = dict(dynamic_info)
        static_common_info.pop("context_variant", None)
        dynamic_common_info.pop("context_variant", None)
        if canonical_json(static_common_info) != canonical_json(dynamic_common_info):
            raise BuildError(f"Pair {static_info['pair_id']} differs outside context_variant metadata")
        for key in ("data_source", "ability", "reward_model"):
            if canonical_json(static[key]) != canonical_json(dynamic[key]):
                raise BuildError(f"Pair {static_info['pair_id']} differs in {key}")
        static_question = str(static["prompt"][0]["content"]).rsplit("\nQuestion: ", 1)[-1]
        dynamic_question = str(dynamic["prompt"][0]["content"]).rsplit("\nQuestion: ", 1)[-1]
        if static_question != dynamic_question:
            raise BuildError(f"Pair {static_info['pair_id']} has different current queries")


def _safe_audit_name(dialogue_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", dialogue_id)


def _write_parquet(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    pd.DataFrame(rows).to_parquet(temporary, index=False)
    os.replace(temporary, path)


def _write_jsonl(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    atomic_write_text(path, "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows))


